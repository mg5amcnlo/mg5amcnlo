      SUBROUTINE SMATRIX3_MULTI(P_MULTI, HEL_RAND, COL_RAND, CHANNELS,
     $  OUT, SELECTED_HEL, SELECTED_COL, VECSIZE_USED)
      USE OMP_LIB
      IMPLICIT NONE

      INCLUDE 'nexternal.inc'
