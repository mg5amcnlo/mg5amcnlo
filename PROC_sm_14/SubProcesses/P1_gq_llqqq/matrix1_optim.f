      DATA (NHEL(I,14),I=0,7) /69, 1, 1, 1,-1, 1,-1, 1/
      DATA (NHEL(I,15),I=0,7) /72, 1, 1, 1,-1, 1, 1,-1/
      DATA (NHEL(I,16),I=0,7) /91, 1, 1,-1, 1,-1, 1, 1/
      DATA (NHEL(I,17),I=0,7) /93, 1, 1,-1, 1, 1,-1, 1/
      DATA (NHEL(I,18),I=0,7) /96, 1, 1,-1, 1, 1, 1,-1/
      DATA (NHEL(I,19),I=0,7) /97, 1,-1, 1,-1,-1,-1, 1/
      DATA (NHEL(I,20),I=0,7) /100, 1,-1, 1,-1,-1, 1,-1/
      DATA (NHEL(I,21),I=0,7) /102, 1,-1, 1,-1, 1,-1,-1/
      DATA (NHEL(I,22),I=0,7) /121, 1,-1,-1, 1,-1,-1, 1/
      DATA (NHEL(I,23),I=0,7) /124, 1,-1,-1, 1,-1, 1,-1/
      DATA (NHEL(I,24),I=0,7) /126, 1,-1,-1, 1, 1,-1,-1/
      DATA IDEN/192/

C     ----------
C     BEGIN CODE
C     ----------

      DO I=1,NEXTERNAL
        JC(I) = +1
      ENDDO

      IF (multi_channel) THEN
        DO I=1,NDIAGS
          AMP2(I)=0D0
        ENDDO
      ENDIF
      JAMP2(0)=4
      DO I=1,INT(JAMP2(0))
        JAMP2(I)=0D0
      ENDDO


      ANS = 0D0

      TS(:) = 0d0

      call MATRIX1(P ,JC(1), TS, AMP2, JAMP2, IVEC)
      DO I=1,NCOMB     
        T=TS(I)  
        DO JJ=1,nincoming
          IF(POL(JJ).NE.1d0.AND.NHEL(JJ,I).EQ.INT(SIGN(1d0,POL(JJ))))
     $      THEN
            T=T*ABS(POL(JJ))*NB_SPIN_STATE_IN(JJ)/2d0    !  NB_SPIN_STATE(JJ)/2d0 is added for polarised beam
          ELSE IF(POL(JJ).NE.1d0)THEN
            T=T*(2d0-ABS(POL(JJ)))*NB_SPIN_STATE_IN(JJ)/2d0
          ENDIF
        ENDDO
        ANS=ANS+DABS(T)
        TS(I)=T
      ENDDO

      IF (ANS.ne.0d0) THEN
        SUMHEL=0d0
        DO I=1,NCOMB
          SUMHEL=SUMHEL+DABS(TS(I))/ANS
          IF(RHEL.LT.SUMHEL)THEN
            IHEL = NHEL(0,I)    !  this returns the id of the helicity before helicity recycling
C           WRITE(HEL_BUFF,'(20i5)')(NHEL(II,I),II=1,NEXTERNAL)
C           Set right sign for ANS, based on sign of chosen helicity
            ANS=DSIGN(ANS,TS(I))
            GOTO 10
          ENDIF
        ENDDO
 10     CONTINUE   
      ENDIF
      IF (MULTI_CHANNEL) THEN
        XTOT=0D0
        DO I=1,LMAXCONFIGS
          J = CONFSUB(1, I)
          if (J.ne.0)then
            if (sde_strat.eq.1)then
              AMP2(J) = AMP2(J) * GET_CHANNEL_CUT(P, I)
            else
              AMP2(J) = GET_CHANNEL_CUT(P, I)
            endif
            XTOT=XTOT+AMP2(J)

          endif
        ENDDO
        IF (XTOT.NE.0D0) THEN
          ANS=ANS*AMP2(channel)/XTOT
        ELSE IF(ANS.ne.0d0) THEN
          write(*,*) 'Problem in the multi-channeling. All amp2 are'
     $     //' zero but not the total matrix-element'
          stop 1
        ENDIF
      ENDIF
      ANS=ANS/DBLE(IDEN)

      call select_color(rcol, jamp2, iconfig,1,  icol)

      END


