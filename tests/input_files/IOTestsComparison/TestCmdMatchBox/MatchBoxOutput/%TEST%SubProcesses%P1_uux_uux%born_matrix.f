      JAMP(1,1) = (1.666666666666667D-01)*AMP(1)+(5.000000000000000D
     $ -01)*AMP(2)
      JAMP(2,1) = (-5.000000000000000D-01)*AMP(1)+(-1.666666666666667D
     $ -01)*AMP(2)
      LNJAMP(1,1) = (5.000000000000000D-01)*AMP(2)
      LNJAMP(2,1) = (-5.000000000000000D-01)*AMP(1)

