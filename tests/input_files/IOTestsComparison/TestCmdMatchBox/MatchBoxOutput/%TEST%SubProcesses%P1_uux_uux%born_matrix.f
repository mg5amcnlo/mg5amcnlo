      SUBROUTINE MG5_1_MATRIX(P,NHEL,IC,FLAV_IDX,RES)
      USE MODEL_OBJECT
C     
C     Generated by MadGraph7 v. %(version)s, %(date)s
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     Returns amplitude squared summed/avg over colors
C     for the point with external lines W(0:6,NEXTERNAL)
C     
C     Process: u u~ > u u~ [ virt = QCD ] @1
C     
      USE ALOHA_OBJECT
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=2)
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=4)
      INTEGER    NWAVEFUNCS, NCOLOR
      PARAMETER (NWAVEFUNCS=5, NCOLOR=2)
      INTEGER NAMPSO, NSQAMPSO
      PARAMETER (NAMPSO=1, NSQAMPSO=1)
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      COMPLEX*16 IMAG1
      PARAMETER (IMAG1=(0D0,1D0))
C     
C     ARGUMENTS 
C     
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL), IC(NEXTERNAL)
C     The HELAS calls below take FLAVOR, which the block that follows
C     rebuilds from FLAV_IDX -- one column of the flavor table, i.e.
C      one of
C     the flavor combinations this (possibly merged) matrix element
C      covers.
      INTEGER FLAV_IDX
      REAL*8 RES(NSQAMPSO)
C     
C     LOCAL VARIABLES
C     
      INTEGER I,J,M,N
      COMPLEX*16 ZTEMP
      INTEGER CF(NCOLOR*(NCOLOR+1))
      INTEGER CF_INDEX, DENOM
      COMPLEX*16 AMP(NGRAPHS)
      COMPLEX*16 JAMP(NCOLOR,NAMPSO), LNJAMP(NCOLOR,NAMPSO)
      COMPLEX*16 TMP_JAMP(0)
      COMMON/MG5_1_JAMP/JAMP,LNJAMP
      TYPE(ALOHA) W(NWAVEFUNCS)
      COMPLEX*16 DUM0,DUM1
      DATA DUM0, DUM1/(0D0, 0D0), (1D0, 0D0)/
      INTEGER FLAVOR(NEXTERNAL)
C     Flavor table for the FLAV_IDX -> FLAVOR rebuild.
      INTEGER NMASK_FLAV
      PARAMETER (NMASK_FLAV=1)
      INTEGER MASK_J
      INTEGER FLAV_TABLE(NEXTERNAL, NMASK_FLAV)
      DATA FLAV_TABLE / 1, 1, 1, 1 /
C     
C     FUNCTION
C     
      INTEGER MG5_1_SQSOINDEX
C     
C     GLOBAL VARIABLES
C     
      INCLUDE 'coupl.inc'
C     
C     COLOR DATA
C     
      DATA DENOM/1/
      DATA (CF(I),I=  1,  2) /9,6/
C     1 T(2,1) T(3,4)
      DATA (CF(I),I=  3,  3) /9/
C     1 T(2,4) T(3,1)
C     ----------
C     BEGIN CODE
C     ----------
C     Rebuild FLAVOR(NEXTERNAL) from the resolved flavor index.
      IF (FLAV_IDX .GE. 1 .AND. FLAV_IDX .LE. NMASK_FLAV) THEN
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, FLAV_IDX)
        ENDDO
      ELSE
        DO MASK_J = 1, NEXTERNAL
          FLAVOR(MASK_J) = FLAV_TABLE(MASK_J, 1)
        ENDDO
      ENDIF
      CALL IXXXXX(P(0,1),ZERO,NHEL(1),+1, FLAVOR(1),W(1))
      CALL OXXXXX(P(0,2),ZERO,NHEL(2),-1, FLAVOR(2),W(2))
      CALL OXXXXX(P(0,3),ZERO,NHEL(3),+1, FLAVOR(3),W(3))
      CALL IXXXXX(P(0,4),ZERO,NHEL(4),-1, FLAVOR(4),W(4))
      CALL FFV1P0_3(W(1),W(2),GC_5,ZERO,ZERO,W(5))
C     Amplitude(s) for diagram number 1
      CALL FFV1_0(W(4),W(3),W(5),GC_5,AMP(1))
      CALL FFV1P0_3(W(1),W(3),GC_5,ZERO,ZERO,W(5))
C     Amplitude(s) for diagram number 2
      CALL FFV1_0(W(4),W(2),W(5),GC_5,AMP(2))
C     JAMPs contributing to orders QCD=2
      JAMP(1,1) = (1.666666666666667D-01)*AMP(1)+(5.000000000000000D
     $ -01)*AMP(2)
      JAMP(2,1) = (-5.000000000000000D-01)*AMP(1)+(-1.666666666666667D
     $ -01)*AMP(2)
      LNJAMP(1,1) = (5.000000000000000D-01)*AMP(2)
      LNJAMP(2,1) = (-5.000000000000000D-01)*AMP(1)

      RES(:) = 0.D0
      DO M = 1, NAMPSO
        CF_INDEX = 0
        DO I = 1, NCOLOR
          ZTEMP = (0.D0,0.D0)
          DO J = I, NCOLOR
            CF_INDEX = CF_INDEX +1
            ZTEMP = ZTEMP + CF(CF_INDEX)*JAMP(J,M)
          ENDDO
          DO N = 1, NAMPSO
            RES(MG5_1_SQSOINDEX(M,N)) = RES(MG5_1_SQSOINDEX(M,N)) +
     $        ZTEMP*DCONJG(JAMP(I,N))
          ENDDO
        ENDDO
      ENDDO
      RES(:) = RES(:)/DENOM
      END
































      SUBROUTINE MG5_1_BORN(P,NHEL,FLAVOR)
      USE MODEL_OBJECT
C     
C     Generated by MadGraph7 v. %(version)s, %(date)s
C     By the MadGraph7 Development Team
