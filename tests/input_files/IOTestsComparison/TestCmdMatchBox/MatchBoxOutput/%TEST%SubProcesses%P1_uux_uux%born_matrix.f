            LNJAMP(I,M) = (0D0, 0D0)
          ENDDO
        ENDDO
        RETURN
      ENDIF
C     Rebuild FLAVOR(NEXTERNAL) from the resolved flavor index.
      IF (FLAV_IDX .GE. 1 .AND. FLAV_IDX .LE. NMASK_FLAV) THEN
