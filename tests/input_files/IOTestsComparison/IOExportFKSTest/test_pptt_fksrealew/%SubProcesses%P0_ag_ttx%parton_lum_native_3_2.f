      SUBROUTINE DLUM_NATIVE_3_2(LUM)
      IMPLICIT NONE
      INCLUDE 'genps.inc'
      INCLUDE 'nexternal.inc'
      DOUBLE PRECISION       CONV
      PARAMETER (CONV=389379660D0)  !CONV TO PICOBARNS             
      DOUBLE PRECISION LUM
      INTEGER I, ICROSS,LP
      DOUBLE PRECISION A1
      DOUBLE PRECISION D2,S2
      DOUBLE PRECISION PHOTONPDFSQUARE
      DOUBLE PRECISION PDG2PDF
      INTEGER              IPROC
      DOUBLE PRECISION PD(0:MAXPROC)
      COMMON /SUBPROC/ PD, IPROC
      INCLUDE 'coupl.inc'
      INCLUDE 'run.inc'
      INTEGER IMIRROR
      COMMON/CMIRROR/IMIRROR
      INCLUDE 'eepdf.inc'
      DOUBLE PRECISION EE_COMP_PROD
      DOUBLE PRECISION DUMMY_COMPONENTS(N_EE)
      DOUBLE PRECISION A1_COMPONENTS(N_EE)
      DOUBLE PRECISION D2_COMPONENTS(N_EE),S2_COMPONENTS(N_EE)
      INTEGER I_EE
      INCLUDE '../../Source/PDF/pdf.inc'
      DATA A1/1*1D0/
      DATA D2,S2/2*1D0/
      DATA ICROSS/1/
      LUM = 0D0
      IF (ABS(LPP(1)) .GE. 1) THEN
        A1=PDG2PDF(LPP(1),7,1,XBK(1),DSQRT(Q2FACT(1)))
        IF ((ABS(LPP(1)).EQ.4.OR.ABS(LPP(1)).EQ.3)   
     $    .AND.PDLABEL.NE.'none') A1_COMPONENTS(1:N_EE) =    
     $    EE_COMPONENTS(1:N_EE)
      ENDIF
      IF (ABS(LPP(2)) .GE. 1) THEN
        D2=PDG2PDF(LPP(2),1,2,XBK(2),DSQRT(Q2FACT(2)))
        IF ((ABS(LPP(2)).EQ.4.OR.ABS(LPP(2)).EQ.3)   
     $    .AND.PDLABEL.NE.'none') D2_COMPONENTS(1:N_EE) =    
     $    EE_COMPONENTS(1:N_EE)
        S2=PDG2PDF(LPP(2),3,2,XBK(2),DSQRT(Q2FACT(2)))
        IF ((ABS(LPP(2)).EQ.4.OR.ABS(LPP(2)).EQ.3)   
     $    .AND.PDLABEL.NE.'none') S2_COMPONENTS(1:N_EE) =    
     $    EE_COMPONENTS(1:N_EE)
      ENDIF
      PD(0) = 0D0
      IPROC = 0
      IPROC=IPROC+1  ! a d > t t~ d
      PD(IPROC) = A1*D2
      IF (ABS(LPP(1)).EQ.ABS(LPP(2)).AND. (ABS(LPP(1)) 
     $  .EQ.3.OR.ABS(LPP(1)).EQ.4).AND.PDLABEL.NE.'none')PD(IPROC) 
     $  =EE_COMP_PROD(A1_COMPONENTS,D2_COMPONENTS)
      IPROC=IPROC+1  ! a s > t t~ s
      PD(IPROC) = A1*S2
      IF (ABS(LPP(1)).EQ.ABS(LPP(2)).AND. (ABS(LPP(1)) 
     $  .EQ.3.OR.ABS(LPP(1)).EQ.4).AND.PDLABEL.NE.'none')PD(IPROC) 
     $  =EE_COMP_PROD(A1_COMPONENTS,S2_COMPONENTS)
      DO I=1,IPROC
        IF (NINCOMING.EQ.2) THEN
          LUM = LUM + PD(I) * CONV
        ELSE
          LUM = LUM + PD(I)
        ENDIF
      ENDDO
      RETURN
      END
