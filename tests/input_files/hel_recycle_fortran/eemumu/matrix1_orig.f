C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     MadGraph7 for Madevent Version
C     
C     Returns amplitude squared -- no average over initial
C      state/symmetry factor
C     and helicities
C     for the point in phase space P(0:3,NEXTERNAL)
C     
C     Process: _anti_lepton _lepton > _anti_lepton _lepton WEIGHTED<=4
C      @1
C     
      USE DISCRETESAMPLER
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INCLUDE 'genps.inc'
      INCLUDE 'maxconfigs.inc'
      INCLUDE 'nexternal.inc'
      INCLUDE 'maxamps.inc'
      INCLUDE '../../Source/vector.inc'  ! defines VECSIZE_MEMMAX
      INCLUDE 'run.inc'
      INTEGER                 NCOMB
      PARAMETER (             NCOMB=16)
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=2)
      INTEGER    NDIAGS
      PARAMETER (NDIAGS=2)
      INTEGER    THEL
      PARAMETER (THEL=2*NCOMB)
C     
C     ARGUMENTS 
C     
      REAL*8 P(0:3,NEXTERNAL),ANS
      DOUBLE PRECISION RHEL  ! random number for selecting helicity
      DOUBLE PRECISION RCOL  ! random number for selecting helicity
      INTEGER CHANNEL  ! channel to keep for the multi-channel
      INTEGER IVEC  ! for using the correct coupling
      INTEGER IFLAV
C     
C     output argument
C     
      INTEGER IHEL, ICOL
C     
C     global (due to reading writing)
C     
C     Good-helicity filter is per (helicity, flavor, subprocess): a
C      helicity
C     that is zero for one merged flavor but non-zero for another must
C      not be
C     dropped, so GOODHEL/NTRY carry an extra MAXFLAVPERPROC (IFLAV)
C      dimension.
C     NTRY is also kept per beam orientation (IM = IMIRROR), so that
C      each
C     orientation gets its own MAXTRIES scan: a helicity can vanish in
C      one
C     orientation only (e.g. q q~ > z with the Z at rest), and in
C      vector mode
C     the first MAXTRIES events can all share one orientation.
      LOGICAL GOODHEL(NCOMB, MAXFLAVPERPROC, MAXSPROC)
      INTEGER NTRY(2, MAXFLAVPERPROC, MAXSPROC)
      COMMON/BLOCK_GOODHEL/NTRY,GOODHEL

C     
C     LOCAL VARIABLES 
C     
      INTEGER CONFSUB(MAXSPROC,LMAXCONFIGS)
      INCLUDE 'config_subproc_map.inc'
      INTEGER NHEL(NEXTERNAL,NCOMB)
      INTEGER ISHEL
      REAL*8 T,MATRIX1
      REAL*8 R,SUMHEL,TS(NCOMB)
      INTEGER I,IDEN
      INTEGER FLAVOR(NEXTERNAL)
      INTEGER FLAVOR_FOR_SYM(NEXTERNAL)
C     Per-row FLAVOR lookup used by BROKEN_SYM. The IFLAV-indexed
C      FLAVOR
C     table above can collapse distinct same-flavor / different-flavor
C     leshouche rows that share the same coupling group; BROKEN_SYM
C      needs
C     row-level information to apply the identical-particle correction.
      INTEGER FLAVOR_ROW(NEXTERNAL,1)
      DATA (FLAVOR_ROW(I,  1),I=  1, NEXTERNAL) /1, 1, 2, 2/

      INTEGER IPSEL
      COMMON /SUBPROC/ IPSEL
      REAL*8 HWGT, XTOT, XTRY, XREJ, XR, YFRAC(0:NCOMB)
      INTEGER NGOOD
      INTEGER J, JJ
      INTEGER NB_FAIL
      SAVE NB_FAIL
      DATA NB_FAIL /0/
      DOUBLE PRECISION GET_CHANNEL_CUT
      EXTERNAL GET_CHANNEL_CUT

C     
C     This is just to temporarily store the reference grid for
C      helicity of the DiscreteSampler so as to obtain its number of
C      entries with ref_helicity_grid%n_tot_entries
      TYPE(SAMPLEDDIMENSION) REF_HELICITY_GRID
C     
C     GLOBAL VARIABLES
C     
      LOGICAL INIT_MODE
      COMMON /TO_DETERMINE_ZERO_HEL/INIT_MODE
      DOUBLE PRECISION AMP2(MAXAMPS), JAMP2(0:MAXFLOW)


      INTEGER NB_SPIN_STATE_IN(2)
      COMMON /NB_HEL_STATE/ NB_SPIN_STATE_IN

      INTEGER IMIRROR, IPROC
      COMMON/TO_MIRROR/ IMIRROR,IPROC
      INTEGER IM

C     included vi run.inc    
C     double precision tmin_for_channel	
C     integer sde_strat ! 1 means standard single diagram enhancement
C      strategy,
C     2 means approximation by the	denominator of the propagator
C     common/TO_CHANNEL_STRAT/tmin_for_channel,	sde_strat

      REAL*8 POL(2)
      COMMON/TO_POLARIZATION/ POL

      INTEGER          ISUM_HEL
      LOGICAL                    MULTI_CHANNEL
      COMMON/TO_MATRIX/ISUM_HEL, MULTI_CHANNEL
      INTEGER MAPCONFIG(0:LMAXCONFIGS), ICONFIG
      COMMON/TO_MCONFIGS/MAPCONFIG, ICONFIG
      DATA XTRY, XREJ /0,0/
      DATA NGOOD /0/
      DATA ISHEL/0/
      SAVE YFRAC
      DATA (NHEL(I,   1),I=1,4) /-1, 1, 1,-1/
      DATA (NHEL(I,   2),I=1,4) /-1, 1, 1, 1/
      DATA (NHEL(I,   3),I=1,4) /-1, 1,-1,-1/
      DATA (NHEL(I,   4),I=1,4) /-1, 1,-1, 1/
      DATA (NHEL(I,   5),I=1,4) /-1,-1, 1,-1/
      DATA (NHEL(I,   6),I=1,4) /-1,-1, 1, 1/
      DATA (NHEL(I,   7),I=1,4) /-1,-1,-1,-1/
      DATA (NHEL(I,   8),I=1,4) /-1,-1,-1, 1/
      DATA (NHEL(I,   9),I=1,4) / 1, 1, 1,-1/
      DATA (NHEL(I,  10),I=1,4) / 1, 1, 1, 1/
      DATA (NHEL(I,  11),I=1,4) / 1, 1,-1,-1/
      DATA (NHEL(I,  12),I=1,4) / 1, 1,-1, 1/
      DATA (NHEL(I,  13),I=1,4) / 1,-1, 1,-1/
      DATA (NHEL(I,  14),I=1,4) / 1,-1, 1, 1/
      DATA (NHEL(I,  15),I=1,4) / 1,-1,-1,-1/
      DATA (NHEL(I,  16),I=1,4) / 1,-1,-1, 1/
      DATA IDEN/ 4/

C     To be able to control when the matrix<i> subroutine can add
C      entries to the grid for the MC over helicity configuration
      LOGICAL ALLOW_HELICITY_GRID_ENTRIES
      COMMON/TO_ALLOW_HELICITY_GRID_ENTRIES/ALLOW_HELICITY_GRID_ENTRIES
C     
C     FUNCTION
C     
      INTEGER BROKEN_SYM1
C     ----------
C     BEGIN CODE
C     ----------
      CALL GET_FLAVOR1(IFLAV, FLAVOR)
C     beam orientation of this event (1 if the caller did not set
C      TO_MIRROR)
      IM = IMIRROR
      IF (IM.NE.2) IM = 1
      NTRY(IM,IFLAV,1)=NTRY(IM,IFLAV,1)+1

      IF (MULTI_CHANNEL) THEN
        DO I=1,NDIAGS
          AMP2(I)=0D0
        ENDDO
      ENDIF
      JAMP2(0)=1
      DO I=1,INT(JAMP2(0))
        JAMP2(I)=0D0
      ENDDO
      ANS = 0D0
      DO I=1,NCOMB
        TS(I)=0D0
      ENDDO

C     If the helicity grid status is 0, this means that it is not yet
C      initialized.
C     If HEL_PICKED==-1, this means that calls to other matrix<i>
C      where in initialization mode as well for the helicity.
      IF ((ISHEL.EQ.0.AND.ISUM_HEL.EQ.0)
     $ .OR.(DS_GET_DIM_STATUS('Helicity').EQ.0).OR.(HEL_PICKED.EQ.-1))
     $  THEN
        DO I=1,NCOMB
          IF (GOODHEL(I,IFLAV,1) .OR. NTRY(IM,IFLAV,1)
     $     .LE.MAXTRIES.OR.(ISUM_HEL.NE.0)) THEN
            T=MATRIX1(P ,NHEL(1,I),IFLAV,I,AMP2, JAMP2, IVEC)

            DO JJ=1,NINCOMING
C             NB_SPIN_STATE_IN/2 avoids a double counting
C             of an explicit polarisation in the process
              IF(POL(JJ).NE.1D0.AND.NHEL(JJ,I).EQ.INT(SIGN(1D0,POL(JJ))
     $         )) THEN
                T=T*ABS(POL(JJ))*NB_SPIN_STATE_IN(JJ)/2D0
              ELSE IF(POL(JJ).NE.1D0)THEN
                T=T*(2D0-ABS(POL(JJ)))*NB_SPIN_STATE_IN(JJ)/2D0
              ENDIF
            ENDDO

            IF (ISUM_HEL.NE.0.AND.DS_GET_DIM_STATUS('Helicity')
     $       .EQ.0.AND.ALLOW_HELICITY_GRID_ENTRIES) THEN
              CALL DS_ADD_ENTRY('Helicity',I,T)
            ENDIF
            ANS=ANS+DABS(T)
            TS(I)=T
          ENDIF
        ENDDO
        IF(NTRY(IM,IFLAV,1).EQ.(MAXTRIES+1)
     $   .AND.DS_GET_DIM_STATUS('Helicity').NE.-1) THEN
          CALL RESET_CUMULATIVE_VARIABLE()  ! avoid biais of the initialization
        ENDIF
        IF (ISUM_HEL.NE.0) THEN
C         We set HEL_PICKED to -1 here so that later on, the call to
C          DS_add_point in dsample.f does not add anything to the grid
C          since it was already done here.
          HEL_PICKED = -1
C         For safety, hardset the helicity sampling jacobian to 0.0d0
C          to make sure it is not .
          HEL_JACOBIAN   = 1.0D0
C         We don't want to re-update the helicity grid if it was
C          already updated by another matrix<i>, so we make sure that
C          the reference grid is empty.
          REF_HELICITY_GRID = DS_GET_DIMENSION(REF_GRID,'Helicity')
          IF((DS_GET_DIM_STATUS('Helicity').EQ.1)
     $     .AND.(REF_HELICITY_GRID%N_TOT_ENTRIES.EQ.0)) THEN
C           If we finished the initialization we can update the grid
C            so as to start sampling over it.
C           However the grid will now be filled by dsample with
C            different kind of weights (including pdf, flux, etc...)
C            so by setting the grid_mode of the reference grid to
C            'initialization' we make sure it will be overwritten (as
C            opposed to 'combined') by the running grid at the next
C            update.
            CALL DS_UPDATE_GRID('Helicity')
            CALL DS_SET_GRID_MODE('Helicity','init')
          ENDIF
        ELSE
          IF(NTRY(IM,IFLAV,1).LE.MAXTRIES)THEN
            DO I=1,NCOMB
              IF(INIT_MODE) THEN
                IF (DABS(TS(I)).GT.ANS*LIMHEL/NCOMB) THEN
                  PRINT *, 'Matrix Element/Good Helicity: 1 ', I,
     $              'IMIRROR', IMIRROR
                ENDIF
              ELSE IF (.NOT.GOODHEL(I,IFLAV,1) .AND. (DABS(TS(I))
     $         .GT.ANS*LIMHEL/NCOMB)) THEN
                GOODHEL(I,IFLAV,1)=.TRUE.
                NGOOD = NGOOD +1
                PRINT *,'Added good helicity ',I, 'for process 1'
     $           //' flavor ',IFLAV,' mirror ',IM,TS(I)*NCOMB/ANS,' in'
     $           //' event ',NTRY(IM,IFLAV,1)
              ENDIF
            ENDDO
          ENDIF
          IF(NTRY(IM,IFLAV,1).EQ.MAXTRIES)THEN
            ISHEL=MIN(ISUM_HEL,NGOOD)
          ENDIF
        ENDIF
      ELSE IF (.NOT.INIT_MODE) THEN  ! random helicity 
C       The helicity configuration was chosen already by genps and put
C        in a common block defined in genps.inc.
        I = HEL_PICKED

        T=MATRIX1(P ,NHEL(1,I),IFLAV,I,AMP2, JAMP2, IVEC)


        DO JJ=1,NINCOMING
C         NB_SPIN_STATE_IN/2 avoids a double counting
C         of an explicit polarisation in the process
          IF(POL(JJ).NE.1D0.AND.NHEL(JJ,I).EQ.INT(SIGN(1D0,POL(JJ))))
     $      THEN
            T=T*ABS(POL(JJ))*NB_SPIN_STATE_IN(JJ)/2D0
          ELSE IF(POL(JJ).NE.1D0)THEN
            T=T*(2D0-ABS(POL(JJ)))*NB_SPIN_STATE_IN(JJ)/2D0
          ENDIF
        ENDDO

C       Always one helicity at a time
        ANS = T
C       Include the Jacobian from helicity sampling
        ANS = ANS * HEL_JACOBIAN
        IHEL = HEL_PICKED
      ELSE
        ANS = 1D0
        RETURN
      ENDIF
      IF (ANS.NE.0D0.AND.(ISUM_HEL .NE. 1.OR.HEL_PICKED.EQ.-1)) THEN
C       CALL RANMAR(R) ! rhel passed as input
        SUMHEL=0D0
        DO I=1,NCOMB
          SUMHEL=SUMHEL+DABS(TS(I))/ANS
          IF(RHEL.LT.SUMHEL)THEN
            IHEL = I
C           Set right sign for ANS, based on sign of chosen helicity
            ANS=DSIGN(ANS,TS(I))
            GOTO 10
          ENDIF
        ENDDO
 10     CONTINUE
      ENDIF
      IF (MULTI_CHANNEL) THEN
        XTOT=0D0
        DO I=1,LMAXCONFIGS
          J = CONFSUB(1, I)
          IF (J.NE.0) THEN
            IF(SDE_STRAT.EQ.1) THEN
              AMP2(J) = AMP2(J) * GET_CHANNEL_CUT(P, I)
              XTOT=XTOT+AMP2(J)
            ELSE
              AMP2(J) = GET_CHANNEL_CUT(P, I)
              XTOT=XTOT+AMP2(J)
            ENDIF
          ENDIF
        ENDDO
        IF (XTOT.NE.0D0) THEN
          ANS=ANS*AMP2(CHANNEL)/XTOT
        ELSE IF(ANS.NE.0D0) THEN
          IF(NB_FAIL.GE.10)THEN
            WRITE(*,*) 'Problem in the multi-channeling. All amp2 are'
     $       //' zero but not the total matrix-element'

            STOP 1
          ELSE
            NB_FAIL = NB_FAIL +1
          ENDIF
        ENDIF
      ENDIF
      IF (IPSEL.GE.1.AND.IPSEL.LE.1) THEN
        FLAVOR_FOR_SYM(:) = FLAVOR_ROW(:, IPSEL)
      ELSE
        FLAVOR_FOR_SYM(:) = FLAVOR(:)
      ENDIF
      ANS=ANS/DBLE(IDEN)*BROKEN_SYM1(FLAVOR_FOR_SYM)

      CALL SELECT_COLOR(RCOL, JAMP2, ICONFIG,1,  ICOL, IVEC)

      END


