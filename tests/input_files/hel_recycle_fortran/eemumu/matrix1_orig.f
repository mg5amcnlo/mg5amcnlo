      CALL OXXXXX(P(0,1),ZERO,NHEL(1),-1, FLAVOR(1),W(1))
      CALL IXXXXX(P(0,2),ZERO,NHEL(2),+1, FLAVOR(2),W(2))
      CALL IXXXXX(P(0,3),ZERO,NHEL(3),-1, FLAVOR(3),W(3))
      CALL OXXXXX(P(0,4),ZERO,NHEL(4),+1, FLAVOR(4),W(4))
      CALL FFV1P0_3(W(2),W(1),GC_3,ZERO, FK_ZERO,W(5))
C     Amplitude(s) for diagram number 1
      CALL FFV1_0(W(3),W(4),W(5),GC_3,AMP(1))
      CALL FFV6_2_3(W(2),W(1),GC_FFV_2,GC_FFV_3,MDL_MZ, FK_MDL_WZ,W(5))
C     Amplitude(s) for diagram number 2
      CALL FFV6_2_0(W(3),W(4),W(5),GC_FFV_2,GC_FFV_3,AMP(2))

      JAMP(:,:) = (0D0,0D0)
C     JAMPs contributing to orders ALL_ORDERS=1
      JAMP(1,1) = (-1.000000000000000D+00)*AMP(1)+(-1.000000000000000D
     $ +00)*AMP(2)


      IF(INIT_MODE)THEN
        AMPMAX_ZERO = 0D0
        DO I=1, NGRAPHS
          AMPMAX_ZERO = MAX(AMPMAX_ZERO, ABS(AMP(I)))
        ENDDO
        DO I=1, NGRAPHS
          IF (ABS(AMP(I)).GT.ZEROAMP_TOL*AMPMAX_ZERO) THEN
            ZEROAMP_1(IHEL,I) = .FALSE.
          ENDIF
        ENDDO
      ENDIF

      MATRIX1 = 0.D0
      DO M = 1, NAMPSO
        CF_INDEX = 0
        DO I = 1, NCOLOR
          ZTEMP = (0.D0,0.D0)
          DO J = I, NCOLOR
            CF_INDEX = CF_INDEX + 1
            ZTEMP = ZTEMP + CF(CF_INDEX)*JAMP(J,M)
          ENDDO
          DO N = 1, NAMPSO

            MATRIX1 = MATRIX1 + ZTEMP*DCONJG(JAMP(I,N))

          ENDDO
        ENDDO
      ENDDO
      MATRIX1 = MATRIX1/DENOM

      IF(SDE_STRAT.EQ.1)THEN
        AMP2(1)=AMP2(1)+AMP(1)*DCONJG(AMP(1))
        AMP2(2)=AMP2(2)+AMP(2)*DCONJG(AMP(2))
      ENDIF

      DO I = 1, NCOLOR_FLOW
        DO M = 1, NAMPSO
          DO N = 1, NAMPSO

            JAMP2(I)=JAMP2(I)+DABS(DBLE(JAMP(I,M)*DCONJG(JAMP(I,N))))

          ENDDO
        ENDDO
      ENDDO

      END

      SUBROUTINE PRINT_ZERO_AMP_1()

      IMPLICIT NONE
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=2)

      INTEGER    NCOMB
      PARAMETER (NCOMB=16)

      LOGICAL ZEROAMP_1(NCOMB, NGRAPHS)
      COMMON/TO_ZEROAMP_1/ZEROAMP_1

      INTEGER I,J
      LOGICAL ALL_FALSE

      DO I=1, NGRAPHS
        ALL_FALSE = .TRUE.
        DO J=1,NCOMB
          IF (.NOT.ZEROAMP_1(J, I)) THEN
            ALL_FALSE = .FALSE.
            EXIT
          ENDIF
        ENDDO
        IF (ALL_FALSE) THEN
          WRITE(*,*) 'Amplitude/ZEROAMP:', 1, I
        ELSE
          DO J=1,NCOMB
            IF (ZEROAMP_1(J, I)) THEN
              WRITE(*,*) 'HEL/ZEROAMP:', 1, J  , I
            ENDIF
          ENDDO
        ENDIF
      ENDDO

      RETURN
      END


