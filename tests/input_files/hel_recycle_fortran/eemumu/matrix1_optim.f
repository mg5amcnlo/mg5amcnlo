      SUBROUTINE SMATRIX1(P, IFLAV, RHEL, RCOL, channel, IVEC, ANS,
     $  IHEL, ICOL)
C     
C     Generated by MadGraph7 v. 0.2.1, 2026-09-24
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     MadGraph7 for Madevent Version
C     
C     Returns amplitude squared summed/avg over colors
C     and helicities
C     for the point in phase space P(0:3,NEXTERNAL)
C     potentially times multi-channel weight
C     
C     Process: _anti_lepton _lepton > _anti_lepton _lepton WEIGHTED<=4
C      @1
C     
      use model_object
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      Include 'genps.inc'
      Include 'maxconfigs.inc'
      Include 'nexternal.inc'
      Include 'maxamps.inc'
      INTEGER                 NCOMB         
      PARAMETER (             NCOMB=13)
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=2) 
      INTEGER    NDIAGS
      PARAMETER (NDIAGS=2) 
C     
C     ARGUMENTS 
C     
      REAL*8 P(0:3,NEXTERNAL)
      double precision RHEL    !  random number for selecting helicity
      double precision RCOL    !  random number for selecting helicity
      integer channel    !  channel to keep for the multi-channel
      integer ivec    !  for using the correct coupling
      integer iflav
C     
C     output argument
C     
      integer ihel, icol    !  selected helicity/color
      double precision ans 
C     
C     LOCAL VARIABLES 
C     
      INTEGER CONFSUB(MAXSPROC,LMAXCONFIGS)
      INCLUDE 'config_subproc_map.inc'
      INTEGER NHEL(0:NEXTERNAL,NCOMB)
      REAL*8 T
      REAL*8 R,SUMHEL,TS(NCOMB)
      INTEGER I,IDEN
      INTEGER FLAVOR(NEXTERNAL)
      INTEGER FLAVOR_FOR_SYM(NEXTERNAL)
C     Per-row FLAVOR lookup used by BROKEN_SYM. The IFLAV-indexed
C      FLAVOR
C     table above can collapse distinct same-flavor / different-flavor
C     leshouche rows that share the same coupling group; BROKEN_SYM
C      needs
C     row-level information to apply the identical-particle correction.
      INTEGER FLAVOR_ROW(NEXTERNAL,1)
      DATA (FLAVOR_ROW(i,  1),i=  1, NEXTERNAL) /1, 1, 2, 2/

      INTEGER IPSEL
      COMMON /SUBPROC/ IPSEL
      INTEGER BROKEN_SYM1
      REAL*8 XTOT
      INTEGER  J, JJ
      double precision get_channel_cut
      external get_channel_cut

C     
C     GLOBAL VARIABLES
C     
      include '../../Source/vector.inc'    !  defines VECSIZE_MEMMAX
      DOUBLE PRECISION AMP2(MAXAMPS), JAMP2(0:MAXFLOW)


C     
C     INFORMATION TO WRITE THE HELICITY IN THE EVENT --not memory
C      efficient--
C     
      INTEGER NB_SPIN_STATE_in(2)
      common /nb_hel_state/ nb_spin_state_in

      REAL*8 POL(2)

      COMMON/TO_POLARIZATION/ POL
      double precision tmin_for_channel
      integer sde_strat    !  1 means standard single diagram enhancement strategy,
C     2 means approximation by the	denominator of the propagator
      common/TO_CHANNEL_STRAT/tmin_for_channel,	sde_strat

      INTEGER          ISUM_HEL
      LOGICAL                    MULTI_CHANNEL
      COMMON/TO_MATRIX/ISUM_HEL, MULTI_CHANNEL
      INTEGER MAPCONFIG(0:LMAXCONFIGS), ICONFIG
      COMMON/TO_MCONFIGS/MAPCONFIG, ICONFIG
      
      DATA (NHEL(I,1),I=0,4) /1,-1, 1, 1,-1/
      DATA (NHEL(I,2),I=0,4) /2,-1, 1, 1, 1/
      DATA (NHEL(I,3),I=0,4) /4,-1, 1,-1, 1/
      DATA (NHEL(I,4),I=0,4) /5,-1,-1, 1,-1/
      DATA (NHEL(I,5),I=0,4) /6,-1,-1, 1, 1/
      DATA (NHEL(I,6),I=0,4) /7,-1,-1,-1,-1/
      DATA (NHEL(I,7),I=0,4) /9, 1, 1, 1,-1/
      DATA (NHEL(I,8),I=0,4) /10, 1, 1, 1, 1/
      DATA (NHEL(I,9),I=0,4) /11, 1, 1,-1,-1/
      DATA (NHEL(I,10),I=0,4) /12, 1, 1,-1, 1/
      DATA (NHEL(I,11),I=0,4) /14, 1,-1, 1, 1/
      DATA (NHEL(I,12),I=0,4) /15, 1,-1,-1,-1/
      DATA (NHEL(I,13),I=0,4) /16, 1,-1,-1, 1/
      DATA IDEN/ 4/

C     ----------
C     BEGIN CODE
C     ----------
      CALL GET_FLAVOR1(IFLAV, FLAVOR)

      IF (multi_channel) THEN
        DO I=1,NDIAGS
          AMP2(I)=0D0
        ENDDO
      ENDIF
      JAMP2(0)=1
      DO I=1,INT(JAMP2(0))
        JAMP2(I)=0D0
      ENDDO


      ANS = 0D0

      TS(:) = 0d0

      call MATRIX1(P ,IFLAV, TS, AMP2, JAMP2, IVEC)
      DO I=1,NCOMB     
        T=TS(I)  
        DO JJ=1,nincoming
          IF(POL(JJ).NE.1d0.AND.NHEL(JJ,I).EQ.INT(SIGN(1d0,POL(JJ))))
     $      THEN
            T=T*ABS(POL(JJ))*NB_SPIN_STATE_IN(JJ)/2d0    !  NB_SPIN_STATE(JJ)/2d0 is added for polarised beam
          ELSE IF(POL(JJ).NE.1d0)THEN
            T=T*(2d0-ABS(POL(JJ)))*NB_SPIN_STATE_IN(JJ)/2d0
          ENDIF
        ENDDO
        ANS=ANS+DABS(T)
        TS(I)=T
      ENDDO

      IF (ANS.ne.0d0) THEN
        SUMHEL=0d0
        DO I=1,NCOMB
          SUMHEL=SUMHEL+DABS(TS(I))/ANS
          IF(RHEL.LT.SUMHEL)THEN
            IHEL = NHEL(0,I)    !  this returns the id of the helicity before helicity recycling
C           WRITE(HEL_BUFF,'(20i5)')(NHEL(II,I),II=1,NEXTERNAL)
C           Set right sign for ANS, based on sign of chosen helicity
            ANS=DSIGN(ANS,TS(I))
            GOTO 10
          ENDIF
        ENDDO
 10     CONTINUE   
      ENDIF
      IF (MULTI_CHANNEL) THEN
        XTOT=0D0
        DO I=1,LMAXCONFIGS
          J = CONFSUB(1, I)
          if (J.ne.0)then
            if (sde_strat.eq.1)then
              AMP2(J) = AMP2(J) * GET_CHANNEL_CUT(P, I)
            else
              AMP2(J) = GET_CHANNEL_CUT(P, I)
            endif
            XTOT=XTOT+AMP2(J)

          endif
        ENDDO
        IF (XTOT.NE.0D0) THEN
          ANS=ANS*AMP2(channel)/XTOT
        ELSE IF(ANS.ne.0d0) THEN
          write(*,*) 'Problem in the multi-channeling. All amp2 are'
     $     //' zero but not the total matrix-element'
          stop 1
        ENDIF
      ENDIF
      IF (IPSEL.GE.1.AND.IPSEL.LE.1) THEN
        FLAVOR_FOR_SYM(:) = FLAVOR_ROW(:, IPSEL)
      ELSE
        FLAVOR_FOR_SYM(:) = FLAVOR(:)
      ENDIF
      ANS=ANS/DBLE(IDEN)*BROKEN_SYM1(FLAVOR_FOR_SYM)

      call select_color(rcol, jamp2, iconfig,1,  icol, ivec)

      END


