      DATA (NHEL(I,14),I=0,5) /17,-1,-1,-1, 1,-1/
      DATA (NHEL(I,15),I=0,5) /19,-1,-1,-1,-1,-1/
      DATA (NHEL(I,16),I=0,5) /20,-1,-1,-1,-1, 1/
      DATA (NHEL(I,17),I=0,5) /21,-1,-1, 1, 1,-1/
      DATA (NHEL(I,18),I=0,5) /22,-1,-1, 1, 1, 1/
      DATA (NHEL(I,19),I=0,5) /24,-1,-1, 1,-1, 1/
      DATA (NHEL(I,20),I=0,5) /25,-1, 1,-1, 1,-1/
      DATA (NHEL(I,21),I=0,5) /26,-1, 1,-1, 1, 1/
      DATA (NHEL(I,22),I=0,5) /27,-1, 1,-1,-1,-1/
      DATA (NHEL(I,23),I=0,5) /29,-1, 1, 1, 1,-1/
      DATA (NHEL(I,24),I=0,5) /30,-1, 1, 1, 1, 1/
      DATA (NHEL(I,25),I=0,5) /31,-1, 1, 1,-1,-1/
      DATA (NHEL(I,26),I=0,5) /32,-1, 1, 1,-1, 1/
      DATA IDEN/36/

