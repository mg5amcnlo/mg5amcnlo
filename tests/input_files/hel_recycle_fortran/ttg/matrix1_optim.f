      SUBROUTINE SMATRIX1(P, IFLAV, RHEL, RCOL, channel, IVEC, ANS,
     $  IHEL, ICOL)
C     
C     Generated by MadGraph7 v. 0.2.1, 2026-09-24
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     MadGraph7 for Madevent Version
C     
C     Returns amplitude squared summed/avg over colors
C     and helicities
C     for the point in phase space P(0:3,NEXTERNAL)
C     potentially times multi-channel weight
C     
C     Process: g g > t t~ g WEIGHTED<=3 @1
C     
      use model_object
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      Include 'genps.inc'
      Include 'maxconfigs.inc'
      Include 'nexternal.inc'
      Include 'maxamps.inc'
      INTEGER                 NCOMB         
      PARAMETER (             NCOMB=26)
      INTEGER    NGRAPHS
      PARAMETER (NGRAPHS=18) 
      INTEGER    NDIAGS
      PARAMETER (NDIAGS=16) 
C     
C     ARGUMENTS 
C     
      REAL*8 P(0:3,NEXTERNAL)
      double precision RHEL    !  random number for selecting helicity
      double precision RCOL    !  random number for selecting helicity
      integer channel    !  channel to keep for the multi-channel
      integer ivec    !  for using the correct coupling
      integer iflav
C     
C     output argument
C     
      integer ihel, icol    !  selected helicity/color
      double precision ans 
C     
C     LOCAL VARIABLES 
C     
      INTEGER CONFSUB(MAXSPROC,LMAXCONFIGS)
      INCLUDE 'config_subproc_map.inc'
      INTEGER NHEL(0:NEXTERNAL,NCOMB)
      REAL*8 T
      REAL*8 R,SUMHEL,TS(NCOMB)
      INTEGER I,IDEN
      INTEGER FLAVOR(NEXTERNAL)
      INTEGER FLAVOR_FOR_SYM(NEXTERNAL)
C     Per-row FLAVOR lookup used by BROKEN_SYM. The IFLAV-indexed
C      FLAVOR
C     table above can collapse distinct same-flavor / different-flavor
C     leshouche rows that share the same coupling group; BROKEN_SYM
C      needs
C     row-level information to apply the identical-particle correction.
      INTEGER FLAVOR_ROW(NEXTERNAL,1)
      DATA (FLAVOR_ROW(i,  1),i=  1, NEXTERNAL) /1, 1, 1, 1, 1/

      INTEGER IPSEL
      COMMON /SUBPROC/ IPSEL
      INTEGER BROKEN_SYM1
      REAL*8 XTOT
      INTEGER  J, JJ
      double precision get_channel_cut
      external get_channel_cut

C     
C     GLOBAL VARIABLES
C     
      include '../../Source/vector.inc'    !  defines VECSIZE_MEMMAX
      DOUBLE PRECISION AMP2(MAXAMPS), JAMP2(0:MAXFLOW)


C     
C     INFORMATION TO WRITE THE HELICITY IN THE EVENT --not memory
C      efficient--
C     
      INTEGER NB_SPIN_STATE_in(2)
      common /nb_hel_state/ nb_spin_state_in

      REAL*8 POL(2)

      COMMON/TO_POLARIZATION/ POL
      double precision tmin_for_channel
      integer sde_strat    !  1 means standard single diagram enhancement strategy,
C     2 means approximation by the	denominator of the propagator
      common/TO_CHANNEL_STRAT/tmin_for_channel,	sde_strat

      INTEGER          ISUM_HEL
      LOGICAL                    MULTI_CHANNEL
      COMMON/TO_MATRIX/ISUM_HEL, MULTI_CHANNEL
      INTEGER MAPCONFIG(0:LMAXCONFIGS), ICONFIG
      COMMON/TO_MCONFIGS/MAPCONFIG, ICONFIG
      
      DATA (NHEL(I,1),I=0,5) /1,-1,-1,-1, 1,-1/
      DATA (NHEL(I,2),I=0,5) /2,-1,-1,-1, 1, 1/
      DATA (NHEL(I,3),I=0,5) /4,-1,-1,-1,-1, 1/
      DATA (NHEL(I,4),I=0,5) /5,-1,-1, 1, 1,-1/
      DATA (NHEL(I,5),I=0,5) /6,-1,-1, 1, 1, 1/
      DATA (NHEL(I,6),I=0,5) /7,-1,-1, 1,-1,-1/
      DATA (NHEL(I,7),I=0,5) /9,-1, 1,-1, 1,-1/
      DATA (NHEL(I,8),I=0,5) /10,-1, 1,-1, 1, 1/
      DATA (NHEL(I,9),I=0,5) /11,-1, 1,-1,-1,-1/
