      DATA (NHEL(I,17),I=0,5) /21, 1,-1, 1,-1,-1/
      DATA (NHEL(I,18),I=0,5) /22, 1,-1, 1,-1, 1/
      DATA (NHEL(I,19),I=0,5) /24, 1,-1, 1, 1, 1/
      DATA (NHEL(I,20),I=0,5) /25, 1, 1,-1,-1,-1/
      DATA (NHEL(I,21),I=0,5) /26, 1, 1,-1,-1, 1/
      DATA (NHEL(I,22),I=0,5) /27, 1, 1,-1, 1,-1/
