! Custom energy scales for MG7, in Fortran. Generated by bin/init_custom_func.
!
! It is called once per phase-space point and sets
! the renormalization scale and the factorization scales of the two incoming
! particles in GeV, for one phase-space point. The run card scale_factor is
! applied on top, and fixed scales still take precedence.
!
! Parameters:
! particle_count  number of external particles, incoming ones first
! pdg_ids         PDG ids of the external particles
! momenta         momenta(:, i) = (E, px, py, pz) of particle i in GeV, lab frame
! params          parameters declared in parameters.h, e.g. params%ht_fraction
! ren_scale       output, the renormalization scale
! fact_scale1     output, the factorization scale of the first incoming particle
! fact_scale2     output, the factorization scale of the second incoming particle
!
! Run `make` in this directory to build ../lib/custom_scale.so.

subroutine custom_scale(particle_count, pdg_ids, momenta, params, ren_scale, fact_scale1, fact_scale2) &
    bind(C, name="custom_scale")
    use iso_c_binding
    implicit none
#include "parameters.h"
    integer(c_int), value :: particle_count
    integer(c_int), intent(in) :: pdg_ids(particle_count)
    real(c_double), intent(in) :: momenta(0:3, particle_count)
    type(custom_parameters), intent(in) :: params
    real(c_double), intent(out) :: ren_scale, fact_scale1, fact_scale2
    real(c_double) :: p(0:3)

    ! Example: a fraction of H_T, the scalar sum of the final-state transverse
    ! masses, with X(ht_fraction, 0.5) in parameters.h.
    ! integer :: i
    ! ren_scale = 0d0
    ! do i = 3, particle_count
    !     ren_scale = ren_scale + sqrt(max(momenta(0, i)**2 - momenta(3, i)**2, 0d0))
    ! end do
    ! ren_scale = params%ht_fraction * ren_scale

    ! default: partonic center-of-mass energy sqrt(s_hat) for all scales
    p = momenta(:, 1) + momenta(:, 2)
    ren_scale = sqrt(max(p(0)**2 - p(1)**2 - p(2)**2 - p(3)**2, 0d0))
    fact_scale1 = ren_scale
    fact_scale2 = ren_scale
end subroutine custom_scale
