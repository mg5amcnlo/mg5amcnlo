"""
Custom event bias for MG7, in Python with PyTorch. Generated by bin/init_custom_func.

custom_bias is called once per batch of phase-space points, with one array
entry per point. It returns a float64 tensor of shape (batch,) with
the bias factor b per event. Events are generated according to |w| b,
and written with the weight divided by b, so physical distributions are
unchanged while regions with large b get more events.

It runs on the device of the run, CPU or GPU. On the CPU, MG7 limits torch
to one thread, since it already calls the function from several threads.

Parameters:
momenta     float64 tensor of shape (batch, particle_count, 4), the momenta
            (E, px, py, pz) of the external particles in GeV, lab frame,
            incoming ones first
pdg_ids     int32 tensor of shape (batch, particle_count), their PDG ids
params      the parameters of PARAMETERS, e.g. params.pt0. Their values
            are set in Cards/run_card.toml with
            [custom_functions]
            bias_parameters.pt0 = ...

Enable it in Cards/run_card.toml with
[custom_functions]
bias = "custom_bias/custom_bias.py"
"""

