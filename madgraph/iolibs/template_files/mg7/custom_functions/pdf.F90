! Custom parton density for MG7, in Fortran. Generated by bin/init_custom_func.
!
! It is called once per phase-space point and returns
! x f(x, q), the momentum fraction times the parton density, for the parton
! with PDG id pdg_id (21 for the gluon) in the beam beam_index (0 or 1), at
! momentum fraction x and factorization scale q in GeV. The strong coupling
! still comes from the PDF set in the run card.
!
! Parameters:
! beam_index      index of the beam, 0 or 1
! pdg_id          PDG id of the parton
! x               momentum fraction
! q               factorization scale in GeV
! params          parameters declared in parameters.h, e.g. params%gluon_norm
!
! Run `make` in this directory to build ../lib/custom_pdf.so.

function custom_pdf(beam_index, pdg_id, x, q, params) bind(C, name="custom_pdf") result(value)
    use iso_c_binding
    implicit none
#include "parameters.h"
    integer(c_int), value :: beam_index, pdg_id
    real(c_double), value :: x, q
    type(custom_parameters), intent(in) :: params
    real(c_double) :: value
    real(c_double) :: norm

    ! default: a toy density, replace it with your own. Its gluon
    ! normalization could be a parameter, with X(gluon_norm, 3.) in parameters.h.
    if (pdg_id == 21) then
        norm = 3d0
    else
        norm = 0.5d0
    end if
    value = norm * sqrt(x) * (1d0 - x)**3
end function custom_pdf
