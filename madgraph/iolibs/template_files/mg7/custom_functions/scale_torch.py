"""
Custom energy scales for MG7, in Python with PyTorch. Generated by bin/init_custom_func.

custom_scale is called once per batch of phase-space points, with one array
entry per point. It returns the renormalization scale and the factorization scales
of the two incoming particles in GeV, as a tuple of three float64 tensors of
shape (batch,), or a single one used for all three. The run card scale_factor
is applied on top, and fixed scales still take precedence.

It runs on the device of the run, CPU or GPU. On the CPU, MG7 limits torch
to one thread, since it already calls the function from several threads.

Parameters:
momenta     float64 tensor of shape (batch, particle_count, 4), the momenta
            (E, px, py, pz) of the external particles in GeV, lab frame,
            incoming ones first
pdg_ids     int32 tensor of shape (batch, particle_count), their PDG ids
params      the parameters of PARAMETERS, e.g. params.ht_fraction. Their values
            are set in Cards/run_card.toml with
            [custom_functions]
            scale_parameters.ht_fraction = ...

Enable it in Cards/run_card.toml with
[custom_functions]
scale = "custom_scale/custom_scale.py"
"""

