"""
Custom energy scales for MG7, in Python with numpy. Generated by bin/init_custom_func.

custom_scale is called once per batch of phase-space points, with one array
entry per point. It returns the renormalization scale and the factorization scales
of the two incoming particles in GeV, as a tuple of three float64 arrays of
shape (batch,), or a single one used for all three. The run card scale_factor
is applied on top, and fixed scales still take precedence.

It runs on the CPU only. Use the python-torch template for GPU runs.

Parameters:
momenta     float64 array of shape (batch, particle_count, 4), the momenta
            (E, px, py, pz) of the external particles in GeV, lab frame,
            incoming ones first
pdg_ids     int32 array of shape (batch, particle_count), their PDG ids
params      the parameters of PARAMETERS, e.g. params.ht_fraction. Their values
            are set in Cards/run_card.toml with
            [custom_functions]
            scale_parameters.ht_fraction = ...

Enable it in Cards/run_card.toml with
[custom_functions]
scale = "custom_scale/custom_scale.py"
"""

import numpy as np

FRAMEWORK = "numpy"

# names and default values of the parameters, e.g. {"ht_fraction": 0.5}
PARAMETERS = {}


def custom_scale(momenta, pdg_ids, params):
    # Example: a fraction of H_T, the scalar sum of the final-state transverse
    # masses, for all scales.
    # final = momenta[:, 2:]
    # mt = np.sqrt(np.maximum(final[..., 0] ** 2 - final[..., 3] ** 2, 0.))
    # return params.ht_fraction * mt.sum(axis=1)

    # default: partonic center-of-mass energy sqrt(s_hat) for all scales
    p = momenta[:, 0] + momenta[:, 1]
    scale = np.sqrt(np.maximum(p[:, 0] ** 2 - (p[:, 1:] ** 2).sum(axis=1), 0.))
    return scale, scale, scale
