! Custom cut for MG7, in Fortran. Generated by bin/init_custom_func.
!
! It is called once per phase-space point and returns
! whether one phase-space point passes the cut: true keeps the event, false
! rejects it.
!
! Parameters:
! particle_count  number of external particles, incoming ones first
! pdg_ids         PDG ids of the external particles
! momenta         momenta(:, i) = (E, px, py, pz) of particle i in GeV, lab frame
! params          parameters declared in parameters.h, e.g. params%pt_min
!
! Run `make` in this directory to build ../lib/custom_cut.so.

function custom_cut(particle_count, pdg_ids, momenta, params) bind(C, name="custom_cut") result(value)
    use iso_c_binding
    implicit none
#include "parameters.h"
    integer(c_int), value :: particle_count
    integer(c_int), intent(in) :: pdg_ids(particle_count)
    real(c_double), intent(in) :: momenta(0:3, particle_count)
    type(custom_parameters), intent(in) :: params
    logical(c_bool) :: value

    ! Example: require pT > pt_min for the first final-state particle, with
    ! X(pt_min, 20.) in parameters.h.
    ! value = momenta(1, 3)**2 + momenta(2, 3)**2 > params%pt_min**2

    value = .true.
end function custom_cut
