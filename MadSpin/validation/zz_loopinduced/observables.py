#!/usr/bin/env python3
"""The event-level observables of the ``g g > z z`` loop-induced comparison.

One module, imported by the harvester and by both plotting scripts, so the
definition a number was made with is the definition it is plotted with.  Nothing
here needs MadGraph: it reads Les Houches files and returns numpy arrays.

Every observable is built from the four status-1 charged leptons of an event --
``e+ e- mu+ mu-``, one of each -- and from nothing else.  That is what makes the
two sides comparable: sample B (``g g > e+ e- mu+ mu- / a``, loop-induced) has
no ``z`` in its final state at all, and sample A only has one before MadSpin
decays it, so any observable that mentions a ``z`` would be measurable on one
side and not the other.  The pair masses are *reconstructed*, exactly as an
experiment would have to.

The angular conventions follow the H -> ZZ -> 4l literature
(Gao et al., arXiv:0708.0458), specialised to a ``ZZ`` system that is not a
resonance:

``cos_theta1`` / ``cos_theta2``
    the ``l+`` direction in its own pair's rest frame, measured against that
    pair's direction of flight in the four-lepton rest frame.  The two boosts
    are SEQUENTIAL -- lab -> four-lepton frame -> pair rest frame -- and that is
    not a detail: taking the axis in one frame while boosting the lepton in from
    another composes two non-collinear boosts, and the Wigner rotation of that
    composition makes the angle depend on the observer.  This module got it
    wrong until 2026-08-27; ``_selftest_helicity_frame`` is the guard and
    POLWEIGHT_CLOSURE_DIAGNOSIS.md is the story.  Flat for an
    unpolarised parent; the ``1 + cos^2`` / ``cos`` structure of a real ``Z``
    decay is what a spin-correlated MadSpin mode has to reproduce.  These
    respond to the polarisation of ONE ``Z``.

``cos1cos2``
    their product, and the observable that isolates the correlation *between*
    the two decays.  Each factor is separately odd under ``l+ <-> l-`` for an
    unpolarised parent, so ``<cos theta1 . cos theta2>`` is exactly zero for any
    scheme that decays the two ``z`` independently -- however well that scheme
    gets each ``z``'s own polarisation.  It is therefore the strict test of what
    MadSpin's density matrix carries and nothing else.

``phi_planes``
    the angle between the two decay planes in the four-lepton rest frame,
    signed by the ``(e+ e-)`` flight direction so that it runs over the full
    ``[-pi, pi]``.  Also zero-information for factorised decays -- it is
    generated by the interference between the ``ZZ`` helicity amplitudes -- and
    it is the observable the ``H -> ZZ -> 4l`` literature leads with, which is
    why it is here.

    It turns out **not** to discriminate for this process.  ``gg -> ZZ`` is a
    continuum, not a spin-0 resonance, and once the modulation is integrated
    over the production angle and over ``m_4l`` it averages away: all four
    MadSpin modes and the off-shell truth agree on a flat ``Phi`` to within the
    statistics of 50 000 events.  That is a measurement, not a defect of the
    definition -- ``cos1cos2``, computed from the same boosts, does separate the
    modes -- and it is reported as such in RESULTS.md.

``m_epmum``
    the ``(e+ mu-)`` invariant mass: a cross-pair combination, so it is built
    from one lepton out of each decay and cannot be reproduced by any
    single-``Z`` observable.

``dphi_epmum`` / ``dphi_ee`` / ``dphi_mumu``
    lab-frame azimuthal separations, all three folded to ``[0, pi]`` by the same
    ``abs((dphi + pi) % (2 pi) - pi)`` so that they are directly comparable.
    ``dphi_epmum`` is CROSS-pair -- one lepton from each ``Z`` -- and is the
    cheapest handle on the correlation between the two decays.  The other two
    are INTRA-pair, both leptons out of the same ``Z``, and they are a different
    kind of observable: not a correlation at all, but a proxy for that ``Z``'s
    own transverse momentum.  A ``Z`` at rest in the transverse plane gives
    back-to-back leptons at ``Delta phi = pi``; a boosted ``Z`` collimates them
    towards ``Delta phi = 0``.  So ``dphi_ee`` is a monotone (and rather tight)
    re-reading of ``pt_ee``, which is why it inherits ``pt_ee``'s support
    problem: the ``m_4l < 2 m_Z`` region that no spinmode can reach lives at low
    ``pt`` and therefore at LARGE ``Delta phi``.  See PA_LOWPT_DIAGNOSIS.md;
    the number to quote on these is the agreement on both supports, not one of
    them.  ``dphi_ee`` and ``dphi_mumu`` measure the same thing on the two ``Z``,
    which are equivalent apart from which pair the positional decay rule writes
    first, so they are each other's control.
"""

import gzip
import math

import numpy as np


# --------------------------------------------------------------------------
# Les Houches reading
# --------------------------------------------------------------------------
def _open(path):
    if path.endswith('.gz'):
        return gzip.open(path, 'rt', errors='replace')
    return open(path, 'rt', errors='replace')


def read_lhe(path, want=(-11, 11, -13, 13)):
    """Return ``(weights, {pdg: (N, 4) array of (E, px, py, pz)})``.

    Only status-1 particles are looked at, and exactly one of each pdg in
    ``want`` is required per event -- an event with two ``e+`` would mean the
    positional decay rule did not do what this study assumes, and is a hard
    error rather than something to average over.
    """
    weights = []
    cols = {p: [] for p in want}
    nbad = 0
    with _open(path) as fh:
        inev = False
        wgt = None
        found = {}
        for line in fh:
            s = line.strip()
            if s.startswith('<event'):
                inev, wgt, found = True, None, {}
                continue
            if not inev:
                continue
            if s.startswith('</event>'):
                inev = False
                if set(found) != set(want):
                    nbad += 1
                    continue
                weights.append(wgt)
                for p in want:
                    cols[p].append(found[p])
                continue
            if not s or s.startswith('<') or s.startswith('#'):
                continue
            f = s.split()
            if wgt is None:
                if len(f) >= 6:
                    try:
                        wgt = float(f[2])
                    except ValueError:
                        wgt = None
                continue
            if len(f) < 13:
                continue
            try:
                pdg, status = int(f[0]), int(f[1])
            except ValueError:
                continue
            if status != 1 or pdg not in want:
                continue
            if pdg in found:
                raise ValueError(
                    'two status-1 particles with pdg %d in one event of %s: the '
                    'positional decay rule did not give one e+e- and one mu+mu- '
                    'pair, so this sample is not comparable' % (pdg, path))
            found[pdg] = (float(f[9]), float(f[6]), float(f[7]), float(f[8]))
    if nbad:
        raise ValueError('%d events of %s did not carry exactly one each of '
                         'e+ e- mu+ mu-' % (nbad, path))
    return (np.array(weights, dtype=float),
            {p: np.array(cols[p], dtype=float) for p in want})


# --------------------------------------------------------------------------
# four-vector helpers.  Arrays are (N, 4) with the LHE ordering (E, px, py, pz).
# --------------------------------------------------------------------------
def mass(v):
    m2 = v[:, 0] ** 2 - v[:, 1] ** 2 - v[:, 2] ** 2 - v[:, 3] ** 2
    return np.sqrt(np.clip(m2, 0.0, None))


def pt(v):
    return np.hypot(v[:, 1], v[:, 2])


def boost_to_rest(v, ref):
    """Boost ``v`` into the rest frame of ``ref`` (both (N, 4)).

    ``beta = -p_ref / E_ref`` and ``gamma = E_ref / m_ref``, then

        E'      = gamma (E + beta.p)
        p'_i    = p_i + (gamma - 1)/beta^2 (beta.p) beta_i + gamma beta_i E

    Written out because getting it subtly wrong is easy and silent: an earlier
    version of this function used ``p_ref/m_ref`` where ``beta`` belongs, which
    leaves the *energy* exactly right -- so ``mass()`` of the boosted vector
    still looks plausible -- while multiplying the last term by an extra
    ``gamma``.  Every angular observable in this study is built out of this
    function, so :func:`_selftest_boost` checks it against the three properties
    that pin it down, and is run on import.
    """
    m = mass(ref)
    m = np.where(m > 0, m, 1.0)
    g = ref[:, 0] / m
    e = np.where(ref[:, 0] > 0, ref[:, 0], 1.0)
    bx, by, bz = (-ref[:, 1] / e, -ref[:, 2] / e, -ref[:, 3] / e)
    b2 = bx ** 2 + by ** 2 + bz ** 2
    bp = bx * v[:, 1] + by * v[:, 2] + bz * v[:, 3]
    fac = np.where(b2 > 0, (g - 1.0) / np.where(b2 > 0, b2, 1.0), 0.0)
    out = np.empty_like(v)
    out[:, 0] = g * (v[:, 0] + bp)
    out[:, 1] = v[:, 1] + fac * bp * bx + g * bx * v[:, 0]
    out[:, 2] = v[:, 2] + fac * bp * by + g * by * v[:, 0]
    out[:, 3] = v[:, 3] + fac * bp * bz + g * bz * v[:, 0]
    return out


def _selftest_boost():
    """Three properties that pin :func:`boost_to_rest` down, checked on import.

    1. boosting a vector into its own rest frame leaves ``(m, 0, 0, 0)``;
    2. a boost preserves invariant mass;
    3. the two halves of a two-body system come out back to back in the
       parent's rest frame.

    Property 1 alone is not enough -- it is satisfied by more than one wrong
    formula -- which is why all three are here.
    """
    rng = np.random.default_rng(20260822)
    m = rng.uniform(1.0, 200.0, size=64)
    p3 = rng.normal(0.0, 150.0, size=(64, 3))
    v = np.column_stack([np.sqrt(m ** 2 + (p3 ** 2).sum(1)), p3])
    r = boost_to_rest(v, v)
    assert np.abs(r[:, 1:]).max() < 1e-6, 'boost: self rest frame not at rest'
    assert np.abs(r[:, 0] - m).max() < 1e-8, 'boost: self rest frame energy'

    q3 = rng.normal(0.0, 150.0, size=(64, 3))
    ref = np.column_stack([np.sqrt(300.0 ** 2 + (q3 ** 2).sum(1)), q3])
    b = boost_to_rest(v, ref)
    assert np.abs(mass(b) - mass(v)).max() < 1e-6, 'boost: mass not preserved'

    a, c = v[:32], v[32:]
    par = a + c
    ar, cr = boost_to_rest(a, par), boost_to_rest(c, par)
    assert np.abs(ar[:, 1:] + cr[:, 1:]).max() < 1e-6, \
        'boost: two-body not back to back in the parent rest frame'


_selftest_boost()


def _unit(a):
    n = np.linalg.norm(a, axis=1, keepdims=True)
    return a / np.where(n > 0, n, 1.0)


def phi_of(v):
    return np.arctan2(v[:, 2], v[:, 1])


def _dphi(a, b):
    """Lab azimuthal separation of two momenta, folded to ``[0, pi]``.

    One function so that every ``Delta phi`` in this study is folded the same
    way and the three of them are directly comparable.  The fold is
    ``abs((dphi + pi) % (2 pi) - pi)``, which is the convention ``dphi_epmum``
    has always used; :func:`_selftest_dphi` pins it to the unsigned angle
    between the two transverse projections, ``arccos(cos(phi_a - phi_b))``.
    """
    d = phi_of(a) - phi_of(b)
    return np.abs((d + np.pi) % (2 * np.pi) - np.pi)


def _selftest_dphi():
    """The fold has to be the unsigned transverse angle, and nothing else.

    Two properties, both checked on import:

    1. it agrees with ``arccos(cos(phi_a - phi_b))`` -- i.e. it really is the
       angle in ``[0, pi]``, and the ``%`` does not leave a branch anywhere
       (getting the fold wrong shows up as a step at ``+-pi``, which on a
       distribution that PEAKS at ``pi`` -- and both intra-pair ones do -- would
       land exactly on the interesting bin);
    2. it is invariant under a common rotation about the beam, which is what
       makes it a lab observable one can compare between two samples that were
       generated with different random azimuths.
    """
    rng = np.random.default_rng(20260828)
    n = 512
    pt1 = rng.uniform(0.5, 200.0, size=n)
    pt2 = rng.uniform(0.5, 200.0, size=n)
    f1 = rng.uniform(-np.pi, np.pi, size=n)
    f2 = rng.uniform(-np.pi, np.pi, size=n)

    def _vec(p, f):
        pz = rng.normal(0.0, 300.0, size=n)
        return np.column_stack([np.hypot(p, pz), p * np.cos(f), p * np.sin(f), pz])

    a, b = _vec(pt1, f1), _vec(pt2, f2)
    got = _dphi(a, b)
    assert got.min() >= 0.0 and got.max() <= np.pi + 1e-12, \
        'dphi: not folded into [0, pi]'
    want = np.arccos(np.clip(np.cos(f1 - f2), -1.0, 1.0))
    assert np.abs(got - want).max() < 1e-9, \
        'dphi: the fold is not arccos(cos(dphi)) -- there is a branch left'

    rot = rng.uniform(-np.pi, np.pi, size=n)
    c, s = np.cos(rot), np.sin(rot)
    def _spin(v):
        out = v.copy()
        out[:, 1] = c * v[:, 1] - s * v[:, 2]
        out[:, 2] = s * v[:, 1] + c * v[:, 2]
        return out
    assert np.abs(_dphi(_spin(a), _spin(b)) - got).max() < 1e-9, \
        'dphi: not invariant under a rotation about the beam'


_selftest_dphi()


# --------------------------------------------------------------------------
# The observables
# --------------------------------------------------------------------------
def compute(p):
    """``p`` is the dict returned by :func:`read_lhe`; returns a dict of arrays."""
    ep, em, mup, mum = p[-11], p[11], p[-13], p[13]
    zee = ep + em
    zmm = mup + mum
    four = zee + zmm

    out = {
        'm_ee': mass(zee),
        'm_mumu': mass(zmm),
        'm_4l': mass(four),
        'pt_ee': pt(zee),
        'pt_mumu': pt(zmm),
        'm_epmum': mass(ep + mum),
        'm_epmup': mass(ep + mup),
    }

    # --- delta phi in the lab, all three folded to [0, pi] the same way ------
    # (e+, mu-) is CROSS-pair: the cheapest correlation handle.  (e+, e-) and
    # (mu+, mu-) are INTRA-pair -- both leptons out of one z -- so they are not
    # inter-decay correlations at all; they are a proxy for that z's own pt,
    # anti-correlated with it because a boosted z collimates its decay products
    # and a z at rest gives them back to back.  See the module docstring.
    out['dphi_epmum'] = _dphi(ep, mum)
    out['dphi_ee'] = _dphi(ep, em)
    out['dphi_mumu'] = _dphi(mup, mum)

    # --- cos theta1 / cos theta2: the l+ in its own pair's rest frame, against
    #     that pair's flight direction in the four-lepton rest frame ---
    # The two boosts are SEQUENTIAL -- lab -> four-lepton frame -> pair rest
    # frame -- and they have to be.  Taking the axis in the four-lepton frame
    # while boosting the lepton into the pair's rest frame straight from the lab
    # composes two boosts that are not collinear, and the Wigner rotation of
    # that composition tilts the analysing frame away from the axis by an angle
    # that is zero only when the four-lepton system is at rest in the lab or the
    # pair flies along the boost.  It is not a small effect here: the median
    # tilt on a 13 TeV ``p p > z z`` sample is 8 degrees and the tail reaches 80,
    # and it damps every rank-2 moment towards the isotropic value -- it moved
    # ``f_0`` from 0.170 to 0.210 on the sample of ``polweight_closure.py``.
    # ``_selftest_helicity_frame`` below is the guard: the angle defined this
    # way is a Lorentz invariant of the four momenta, and the mixed composition
    # is not.  See POLWEIGHT_CLOSURE_DIAGNOSIS.md.
    zee_in4 = boost_to_rest(zee, four)
    zmm_in4 = boost_to_rest(zmm, four)
    d1 = _unit(zee_in4[:, 1:4])
    d2 = _unit(zmm_in4[:, 1:4])
    e1 = _unit(boost_to_rest(boost_to_rest(ep, four), zee_in4)[:, 1:4])
    e2 = _unit(boost_to_rest(boost_to_rest(mup, four), zmm_in4)[:, 1:4])
    out['cos_theta1'] = np.clip(np.sum(d1 * e1, axis=1), -1.0, 1.0)
    out['cos_theta2'] = np.clip(np.sum(d2 * e2, axis=1), -1.0, 1.0)
    # The product is the strict INTER-decay correlation: each factor is
    # separately symmetric under l+ <-> l- for an unpolarised parent, so
    # <cos theta1 . cos theta2> can only be non-zero if the two decays are
    # correlated with each other.  A mode that decays each z independently --
    # spinmode = none -- gives exactly zero, no matter what it does to a single
    # z's polarisation, which is what makes this and not Phi the observable
    # that isolates the thing the density matrix carries.
    out['cos1cos2'] = out['cos_theta1'] * out['cos_theta2']

    # --- phi between the two decay planes, in the four-lepton rest frame ---
    ep4 = boost_to_rest(ep, four)[:, 1:4]
    em4 = boost_to_rest(em, four)[:, 1:4]
    mup4 = boost_to_rest(mup, four)[:, 1:4]
    mum4 = boost_to_rest(mum, four)[:, 1:4]
    n1 = _unit(np.cross(ep4, em4))
    n2 = _unit(np.cross(mup4, mum4))
    zdir = _unit(zee_in4[:, 1:4])
    cosphi = np.clip(-np.sum(n1 * n2, axis=1), -1.0, 1.0)
    sign = np.sign(np.sum(zdir * np.cross(n1, n2), axis=1))
    sign = np.where(sign == 0, 1.0, sign)
    out['phi_planes'] = sign * np.arccos(cosphi)

    # --- the polarisation projectors (see POL_0 below) --------------------
    # <pol0_1> is the longitudinal fraction of the (e+ e-) parent, <pol0_2>
    # that of the (mu+ mu-) one, and <pol00> the JOINT longitudinal fraction.
    # They are event-level estimators, so they carry an ordinary error of the
    # mean and the joint one is simply the product of the two single ones.
    out['pol0_1'] = POL_0(out['cos_theta1'])
    out['pol0_2'] = POL_0(out['cos_theta2'])
    out['pol00'] = out['pol0_1'] * out['pol0_2']
    out['polTT'] = (1.0 - out['pol0_1']) * (1.0 - out['pol0_2'])
    return out


