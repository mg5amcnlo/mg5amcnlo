BW_CUT = 15
M_LO = M_Z - BW_CUT * W_Z
M_HI = M_Z + BW_CUT * W_Z
# --------------------------------------------------------------------------
# What a cos(theta) moment is worth: the Z polarisation, and the price of
# using a Z as a spin analyser
# --------------------------------------------------------------------------
# For a Z of helicity ``lambda`` along its own flight direction, decaying to
# massless leptons, the ``l+`` polar angle in the Z rest frame is distributed as
#
#     W_{+-1}(c) = (3/8) (1 + c^2 +- 2 eta_l c)      W_0(c) = (3/4) (1 - c^2)
#
# each normalised to 1 over ``c in [-1, 1]``.  Only the PARITY-VIOLATING term
# carries the analysing power
#
#     eta_l = 2 g_V g_A / (g_V^2 + g_A^2) = (1 - 4 sw2) / (1 - 4 sw2 + 8 sw2^2)
#
# which is small because the Z's coupling to charged leptons is nearly pure
# vector.  The ``(1 + c^2)`` versus ``sin^2`` SHAPE difference carries no
# ``eta_l`` at all.  So the two kinds of moment are not on the same footing:
#
#   * the rank-1 (vector polarisation) moments -- <cos theta>, and the
#     inter-decay <cos theta1 cos theta2> -- are diluted by eta_l and eta_l^2;
#   * the rank-2 (alignment) moments -- <cos^2 theta> and the joint
#     <cos^2 theta1 cos^2 theta2> -- are NOT diluted at all.
#
# Writing f_0 for the longitudinal fraction, the rank-2 relation is
#
#     <cos^2 theta> = (2 - f_0) / 5      i.e.   f_0 = 2 - 5 <cos^2 theta>
#
# and ``POL_0`` below is exactly that, per event, so that <POL_0> = f_0 with an
# ordinary error of the mean.  f_0 = 1/3 is the isotropic (unpolarised) value.
#
# The rank-1 inter-decay one is
#
#     <cos theta1 cos theta2> = (eta_l^2 / 4) C_kk,
#     C_kk = <S_k(1) S_k(2)>, S_k the spin-1 projection on each Z's own
#            helicity axis, eigenvalues +1, 0, -1
#
# so the calibration constant is 4 / eta_l^2 -- NOT the 9 of the t t~ case.
# The 9 there is the spin-1/2 version of the same algebra: for a decay
# (1/2)(1 + kappa c) one gets <c1 c2> = (kappa^2 / 9) C_nn, and kappa = 1 for a
# charged lepton from a top.  For spin 1 the coefficient is 4 even at eta_l = 1.
#
# Numbers: this study runs the MG5 default SM param_card in the on-shell EW
# scheme, where MW is derived from (aEWM1, Gf, MZ) and sw2 = 1 - MW^2/MZ^2.
SM_AEWM1 = 132.507
SM_GF = 1.166390e-05


def _mw_from_sminputs(aewm1=SM_AEWM1, gf=SM_GF, mz=M_Z):
    """MW as the SM UFO builds it: the on-shell solution of the Gf relation."""
    aew = 1.0 / aewm1
    return math.sqrt(mz ** 2 / 2.0
                     + math.sqrt(mz ** 4 / 4.0
                                 - (aew * math.pi * mz ** 2) / (gf * math.sqrt(2.0))))


M_W = _mw_from_sminputs()
SW2 = 1.0 - M_W ** 2 / M_Z ** 2
ETA_L = (1.0 - 4.0 * SW2) / (1.0 - 4.0 * SW2 + 8.0 * SW2 ** 2)


def POL_0(cos_theta):
    """Per-event estimator of the longitudinal fraction: <2 - 5 cos^2> = f_0.

    Not a probability event by event -- it runs from -3 to +2 -- but its mean
    is f_0 exactly, and the mean of the PRODUCT of the two Z's estimators is
    the joint fraction f_00.  1 - POL_0 is the transverse estimator.
    """
    return 2.0 - 5.0 * cos_theta ** 2


def c_kk_from_moment(mean, err):
    """(C_kk, error) from <cos theta1 cos theta2>: C_kk = 4 <c1 c2> / eta_l^2."""
    k = 4.0 / ETA_L ** 2
    return k * mean, k * err


def _selftest_polarisation():
    """The projector has to give 1/3 on an isotropic decay and the right value
    on each pure helicity, or every number built on it is decoration."""
    c = np.linspace(-1.0, 1.0, 200001)

    def _integral(y):
        # trapezoid by hand: np.trapz is deprecated in numpy 2 and
        # np.trapezoid does not exist in numpy 1, and this module has to
        # import under both
        return float(np.sum(0.5 * (y[1:] + y[:-1]) * np.diff(c)))

    def mean(w, v):
        return _integral(w * v) / _integral(w)
    flat = np.ones_like(c)
    w_t = 0.375 * (1.0 + c ** 2)
    w_l = 0.75 * (1.0 - c ** 2)
    assert abs(mean(flat, POL_0(c)) - 1.0 / 3.0) < 1e-6, 'POL_0: isotropic'
    assert abs(mean(w_t, POL_0(c)) - 0.0) < 1e-6, 'POL_0: pure transverse'
    assert abs(mean(w_l, POL_0(c)) - 1.0) < 1e-6, 'POL_0: pure longitudinal'
    # and the eta_l term must not touch it, which is the whole point
    w_p = 0.375 * (1.0 + c ** 2 + 2.0 * ETA_L * c)
    assert abs(mean(w_p, POL_0(c)) - 0.0) < 1e-6, 'POL_0: eta_l leaks in'
    assert 0.20 < ETA_L < 0.24, 'eta_l off its on-shell-scheme value: %r' % ETA_L


_selftest_polarisation()


def _selftest_helicity_frame():
    """``cos_theta1/2`` must be Lorentz INVARIANT, and ``compute`` must not
    disagree with an explicit two-step construction.

    Both angles are built out of nothing but the four lepton momenta and two
    rest frames those momenta define, so no observer can measure a different
    value: boosting the whole event -- along the beam, or in any other
    direction -- has to leave every angular observable of ``compute``
    untouched.  That single property is what the study got wrong for its first
    pass and what this test exists to keep it from getting wrong again.

    The version this replaces took ``d1`` in the four-lepton frame but boosted
    the ``l+`` into its pair's rest frame straight from the LAB.  Those two
    boosts are not collinear, so their composition carries a Wigner rotation:
    the analysing frame is tilted away from the axis by an angle that grows
    with the rapidity of the four-lepton system and vanishes when it is at
    rest.  The observable was therefore a function of the observer, and it
    damped every rank-2 moment towards the isotropic value.  This test FAILS on
    that version -- the boosted event gives different angles -- and passes on
    the sequential one.  See POLWEIGHT_CLOSURE_DIAGNOSIS.md.

    Property 2 pins the frame down positively rather than only forbidding the
    old one: a decay generated as a pure ``sin^2(theta)`` about the parent's
    own direction in the four-lepton frame has to come back with
    ``<cos^2 theta> = 1/5``, which is exactly the closure MadSpin's polarised
    matrix-element weights were failing.
    """
    rng = np.random.default_rng(20260827)
    n = 4000

    # --- a synthetic ZZ -> 4l sample, built in the four-lepton rest frame ---
    m1 = rng.normal(M_Z, 2.5, size=n)
    m2 = rng.normal(M_Z, 2.5, size=n)
    s = (rng.uniform(0.0, 1.0, size=n) ** 2) * 600.0 + m1 + m2 + 20.0
    # back-to-back Z of the pair, isotropic production angle
    e1z = (s ** 2 + m1 ** 2 - m2 ** 2) / (2.0 * s)
    pz = np.sqrt(np.maximum(e1z ** 2 - m1 ** 2, 0.0))
    ct = rng.uniform(-1.0, 1.0, size=n)
    st = np.sqrt(1.0 - ct ** 2)
    fi = rng.uniform(0.0, 2.0 * np.pi, size=n)
    nz = np.column_stack([st * np.cos(fi), st * np.sin(fi), ct])
    Z1 = np.column_stack([e1z, pz[:, None] * nz])
    Z2 = np.column_stack([s - e1z, -pz[:, None] * nz])

    def _decay(parent, m, cos_hel):
        """Two massless daughters, ``cos_hel`` measured against the parent's own
        direction in the frame ``parent`` is written in.  Returns the l+ and l-
        in that same frame."""
        # local triad with z along the parent's direction
        z = _unit(parent[:, 1:4])
        ref = np.tile(np.array([0.0, 0.0, 1.0]), (len(z), 1))
        bad = np.abs(z[:, 2]) > 0.99
        ref[bad] = np.array([1.0, 0.0, 0.0])
        x = _unit(ref - z * np.sum(ref * z, axis=1)[:, None])
        y = np.cross(z, x)
        sh = np.sqrt(1.0 - cos_hel ** 2)
        ph = rng.uniform(0.0, 2.0 * np.pi, size=len(z))
        k = (z * cos_hel[:, None] + x * (sh * np.cos(ph))[:, None]
             + y * (sh * np.sin(ph))[:, None])
        half = m / 2.0
        lp = np.column_stack([half, half[:, None] * k])
        lm = np.column_stack([half, -half[:, None] * k])
        # from the parent rest frame out to the frame ``parent`` lives in
        back = parent.copy()
        back[:, 1:4] *= -1.0
        return boost_to_rest(lp, back), boost_to_rest(lm, back)

    # pure longitudinal: sin^2 theta, drawn by inverting its cumulative
    u = rng.uniform(-1.0, 1.0, size=n)
    cos_hel = 2.0 * np.sin(np.arcsin(u) / 3.0)          # root of (3c - c^3)/2 = u
    ep, em = _decay(Z1, m1, cos_hel)
    mup, mum = _decay(Z2, m2, cos_hel[::-1].copy())
    p = {-11: ep, 11: em, -13: mup, 13: mum}

    got = compute(p)
    assert abs(float(np.mean(got['cos_theta1'] ** 2)) - 0.2) < 5e-3, \
        'helicity frame: a pure sin^2 decay does not give <cos^2 theta> = 1/5 ' \
        '(got %.5f)' % float(np.mean(got['cos_theta1'] ** 2))

    # --- property 1: invariance under an arbitrary boost of the whole event --
    for beta in ((0.0, 0.0, 0.90), (0.0, 0.0, -0.55), (0.31, -0.18, 0.62)):
        b = np.array(beta)
        g = 1.0 / math.sqrt(1.0 - float(b @ b))
        ref = np.tile(np.concatenate([[g], -g * b]), (n, 1))  # boost_to_rest(-beta)
        ref *= 100.0                                          # any positive scale
        moved = {k: boost_to_rest(v, ref) for k, v in p.items()}
        again = compute(moved)
        for name in ('cos_theta1', 'cos_theta2', 'cos1cos2', 'phi_planes'):
            d = float(np.abs(again[name] - got[name]).max())
            assert d < 1e-6, (
                'helicity frame: %s is not Lorentz invariant -- boosting the '
                'event by beta = %s moves it by %.4g. The two boosts into the '
                'pair rest frame have to be sequential (lab -> 4l -> pair); a '
                'mixed composition carries a Wigner rotation.' % (name, beta, d))


