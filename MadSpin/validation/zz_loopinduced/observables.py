def histogram(values, weights, edges):
    """Weighted histogram plus its Monte-Carlo error, both as densities.

    Returned in ``d sigma / d x`` units: the sum of weights in a bin divided by
    the number of events in the *file* (the LHE is IDWTUP = -4, so mean(w) is
    the cross section) and by the bin width.  The error is
    ``sqrt(sum w^2)`` carried through the same normalisation, which is the
    right one for a sample of nearly-equal weights and stays right when
    MadSpin's overweight carry makes them not quite equal.
    """
    n = len(weights)
    s, _ = np.histogram(values, bins=edges, weights=weights)
    s2, _ = np.histogram(values, bins=edges, weights=weights ** 2)
    width = np.diff(edges)
    return s / n / width, np.sqrt(s2) / n / width
